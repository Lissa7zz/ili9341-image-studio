export const DEFAULT_WIDTH = 320;
export const DEFAULT_HEIGHT = 240;
export const MAX_DIMENSION = 1024;

export function clampByte(value) {
  return Math.max(0, Math.min(255, Math.round(Number(value) || 0)));
}

export function rgbToRgb565(red, green, blue) {
  const r = clampByte(red);
  const g = clampByte(green);
  const b = clampByte(blue);
  return ((r & 0xf8) << 8) | ((g & 0xfc) << 3) | (b >> 3);
}

// Canvas pixels are RGBA. The returned bytes are high-byte first, matching
// STM32 little-endian uint16_t storage and the ILI9341 receive order.
export function rgbaToRgb565Bytes(rgba, width, height) {
  if (!(rgba instanceof Uint8ClampedArray)) {
    throw new TypeError("rgba must be a Uint8ClampedArray");
  }

  if (!Number.isInteger(width) || !Number.isInteger(height) || width < 1 || height < 1) {
    throw new RangeError("width and height must be positive integers");
  }

  const expectedLength = width * height * 4;
  if (rgba.length !== expectedLength) {
    throw new RangeError(`Expected ${expectedLength} RGBA bytes, received ${rgba.length}`);
  }

  const output = new Uint8Array(width * height * 2);
  for (let source = 0, target = 0; source < rgba.length; source += 4, target += 2) {
    const color = rgbToRgb565(rgba[source], rgba[source + 1], rgba[source + 2]);
    output[target] = color >> 8;
    output[target + 1] = color & 0xff;
  }

  return output;
}

export function sanitizeIdentifier(value, fallback = "image_rgb565") {
  let name = String(value ?? "")
    .trim()
    .replace(/[^a-zA-Z0-9_]/g, "_")
    .replace(/_+/g, "_");

  if (!name) {
    name = fallback;
  }

  if (/^[0-9]/.test(name)) {
    name = `image_${name}`;
  }

  if (name.length > 64) {
    name = name.slice(0, 64);
  }

  return name;
}

export function isValidCIdentifier(value) {
  return /^[a-zA-Z_][a-zA-Z0-9_]{0,63}$/.test(String(value));
}

function uppercaseIdentifier(identifier) {
  return identifier.toUpperCase();
}

function validateImageSource({ identifier, width, height, data }) {
  if (!(data instanceof Uint8Array)) {
    throw new TypeError("data must be a Uint8Array");
  }

  if (!isValidCIdentifier(identifier)) {
    throw new Error("identifier is not a valid C identifier");
  }

  if (!Number.isInteger(width) || !Number.isInteger(height) || width < 1 || height < 1) {
    throw new RangeError("width and height must be positive integers");
  }

  if (data.length !== width * height * 2) {
    throw new Error("RGB565 data length does not match image dimensions");
  }
}

function createGeneratedComment(sourceName, generatedAt) {
  const timestamp = generatedAt.toISOString().replace(/\.\d{3}Z$/, "Z");
  const safeSource = String(sourceName).replace(/[\r\n*]/g, " ");
  return [
    "/*",
    " * Generated by Pixel2Panel v0.2.0",
    ` * Source: ${safeSource}`,
    ` * Generated: ${timestamp}`,
    " * Format: RGB565, high byte first (STM32 little-endian compatible)",
    " */",
  ];
}

export function createHeader({
  identifier,
  width,
  height,
  data,
  sourceName = "image",
  generatedAt = new Date(),
}) {
  validateImageSource({ identifier, width, height, data });

  const macro = `${uppercaseIdentifier(identifier)}_H`;
  const widthMacro = `${uppercaseIdentifier(identifier)}_WIDTH`;
  const heightMacro = `${uppercaseIdentifier(identifier)}_HEIGHT`;
  const sizeMacro = `${uppercaseIdentifier(identifier)}_DATA_SIZE`;
  const lines = [
    "#ifndef " + macro,
    "#define " + macro,
    "",
    "#include <stdint.h>",
    "",
    ...createGeneratedComment(sourceName, generatedAt),
    "",
    `#define ${widthMacro} ${width}U`,
    `#define ${heightMacro} ${height}U`,
    `#define ${sizeMacro} (${widthMacro} * ${heightMacro} * 2U)`,
    "",
    `extern const uint8_t ${identifier}[${sizeMacro}];`,
    "",
    `#endif /* ${macro} */`,
    "",
  ];

  return lines.join("\n");
}

export function createSource({
  identifier,
  width,
  height,
  data,
  sourceName = "image",
  generatedAt = new Date(),
}) {
  validateImageSource({ identifier, width, height, data });

  const sizeMacro = `${uppercaseIdentifier(identifier)}_DATA_SIZE`;
  const lines = [
    `#include "${identifier}.h"`,
    "",
    ...createGeneratedComment(sourceName, generatedAt),
    "",
    `const uint8_t ${identifier}[${sizeMacro}] =`,
    "{",
  ];

  for (let offset = 0; offset < data.length; offset += 16) {
    const chunk = Array.from(data.subarray(offset, offset + 16), (value) =>
      `0x${value.toString(16).toUpperCase().padStart(2, "0")}U`,
    );
    lines.push(`  ${chunk.join(", ")},`);
  }

  lines.push("};", "");
  return lines.join("\n");
}

function crc32(data) {
  let crc = 0xffffffff;
  for (const value of data) {
    crc ^= value;
    for (let bit = 0; bit < 8; bit++) {
      crc = (crc >>> 1) ^ (crc & 1 ? 0xedb88320 : 0);
    }
  }
  return (crc ^ 0xffffffff) >>> 0;
}

function writeUint16(view, offset, value) {
  view.setUint16(offset, value, true);
}

function writeUint32(view, offset, value) {
  view.setUint32(offset, value, true);
}

function dosDateTime(date) {
  const year = Math.max(1980, date.getFullYear());
  return {
    time:
      (date.getHours() << 11) |
      (date.getMinutes() << 5) |
      Math.floor(date.getSeconds() / 2),
    date: ((year - 1980) << 9) | ((date.getMonth() + 1) << 5) | date.getDate(),
  };
}

export function createZip(files, modifiedAt = new Date()) {
  if (!Array.isArray(files) || files.length === 0) {
    throw new Error("at least one file is required");
  }

  const encoder = new TextEncoder();
  const timestamp = dosDateTime(modifiedAt);
  const localParts = [];
  const centralParts = [];
  const entries = [];
  let localOffset = 0;

  for (const file of files) {
    const name = String(file.name ?? "");
    if (!name) {
      throw new Error("each ZIP entry needs a file name");
    }

    const fileName = encoder.encode(name);
    const fileData =
      file.data instanceof Uint8Array
        ? file.data
        : encoder.encode(String(file.data ?? ""));
    const checksum = crc32(fileData);
    const local = new Uint8Array(30 + fileName.length);
    const localView = new DataView(local.buffer);
    writeUint32(localView, 0, 0x04034b50);
    writeUint16(localView, 4, 20);
    writeUint16(localView, 6, 0x0800);
    writeUint16(localView, 8, 0);
    writeUint16(localView, 10, timestamp.time);
    writeUint16(localView, 12, timestamp.date);
    writeUint32(localView, 14, checksum);
    writeUint32(localView, 18, fileData.length);
    writeUint32(localView, 22, fileData.length);
    writeUint16(localView, 26, fileName.length);
    writeUint16(localView, 28, 0);
    local.set(fileName, 30);
    localParts.push(local, fileData);

    const central = new Uint8Array(46 + fileName.length);
    const centralView = new DataView(central.buffer);
    writeUint32(centralView, 0, 0x02014b50);
    writeUint16(centralView, 4, 20);
    writeUint16(centralView, 6, 20);
    writeUint16(centralView, 8, 0x0800);
    writeUint16(centralView, 10, 0);
    writeUint16(centralView, 12, timestamp.time);
    writeUint16(centralView, 14, timestamp.date);
    writeUint32(centralView, 16, checksum);
    writeUint32(centralView, 20, fileData.length);
    writeUint32(centralView, 24, fileData.length);
    writeUint16(centralView, 28, fileName.length);
    writeUint16(centralView, 30, 0);
    writeUint16(centralView, 32, 0);
    writeUint16(centralView, 34, 0);
    writeUint16(centralView, 36, 0);
    writeUint32(centralView, 38, 0);
    writeUint32(centralView, 42, localOffset);
    central.set(fileName, 46);
    centralParts.push(central);
    entries.push({ local, fileData, central });
    localOffset += local.length + fileData.length;
  }

  const centralSize = centralParts.reduce((sum, part) => sum + part.length, 0);
  const end = new Uint8Array(22);
  const endView = new DataView(end.buffer);
  writeUint32(endView, 0, 0x06054b50);
  writeUint16(endView, 4, 0);
  writeUint16(endView, 6, 0);
  writeUint16(endView, 8, entries.length);
  writeUint16(endView, 10, entries.length);
  writeUint32(endView, 12, centralSize);
  writeUint32(endView, 16, localOffset);
  writeUint16(endView, 20, 0);

  const totalSize =
    localOffset + centralSize + end.length;
  const output = new Uint8Array(totalSize);
  let offset = 0;
  for (const part of localParts) {
    output.set(part, offset);
    offset += part.length;
  }
  for (const part of centralParts) {
    output.set(part, offset);
    offset += part.length;
  }
  output.set(end, offset);
  return output;
}

export function createIco(pngBytes, size = 256) {
  if (!(pngBytes instanceof Uint8Array)) {
    throw new TypeError("pngBytes must be a Uint8Array");
  }

  if (!Number.isInteger(size) || size < 1 || size > 256) {
    throw new RangeError("ICO size must be between 1 and 256");
  }

  const header = new Uint8Array(22);
  const view = new DataView(header.buffer);
  view.setUint16(0, 0, true);
  view.setUint16(2, 1, true);
  view.setUint16(4, 1, true);
  header[6] = size === 256 ? 0 : size;
  header[7] = size === 256 ? 0 : size;
  header[8] = 0;
  header[9] = 0;
  view.setUint16(10, 1, true);
  view.setUint16(12, 32, true);
  view.setUint32(14, pngBytes.length, true);
  view.setUint32(18, header.length, true);

  const output = new Uint8Array(header.length + pngBytes.length);
  output.set(header);
  output.set(pngBytes, header.length);
  return output;
}

export function formatBytes(bytes) {
  if (bytes < 1024) {
    return `${bytes} B`;
  }

  if (bytes < 1024 * 1024) {
    return `${(bytes / 1024).toFixed(1).replace(/\.0$/, "")} KB`;
  }

  return `${(bytes / (1024 * 1024)).toFixed(1).replace(/\.0$/, "")} MB`;
}

export function clampDimension(value) {
  const numeric = Math.round(Number(value));
  if (!Number.isFinite(numeric)) {
    return null;
  }

  if (numeric < 16 || numeric > MAX_DIMENSION) {
    return null;
  }

  return numeric;
}
