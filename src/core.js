export const DEFAULT_WIDTH = 320;
export const DEFAULT_HEIGHT = 240;
export const MAX_DIMENSION = 1024;

export function clampByte(value) {
  return Math.max(0, Math.min(255, Math.round(Number(value) || 0)));
}

export function rgbToRgb565(red, green, blue) {
  const r = clampByte(red);
  const g = clampByte(green);
  const b = clampByte(blue);
  return ((r & 0xf8) << 8) | ((g & 0xfc) << 3) | (b >> 3);
}

// Canvas pixels are RGBA. The returned bytes are high-byte first, matching
// STM32 little-endian uint16_t storage and the ILI9341 receive order.
export function rgbaToRgb565Bytes(rgba, width, height) {
  if (!(rgba instanceof Uint8ClampedArray)) {
    throw new TypeError("rgba must be a Uint8ClampedArray");
  }

  if (!Number.isInteger(width) || !Number.isInteger(height) || width < 1 || height < 1) {
    throw new RangeError("width and height must be positive integers");
  }

  const expectedLength = width * height * 4;
  if (rgba.length !== expectedLength) {
    throw new RangeError(`Expected ${expectedLength} RGBA bytes, received ${rgba.length}`);
  }

  const output = new Uint8Array(width * height * 2);
  for (let source = 0, target = 0; source < rgba.length; source += 4, target += 2) {
    const color = rgbToRgb565(rgba[source], rgba[source + 1], rgba[source + 2]);
    output[target] = color >> 8;
    output[target + 1] = color & 0xff;
  }

  return output;
}

export function sanitizeIdentifier(value, fallback = "image_rgb565") {
  let name = String(value ?? "")
    .trim()
    .replace(/[^a-zA-Z0-9_]/g, "_")
    .replace(/_+/g, "_");

  if (!name) {
    name = fallback;
  }

  if (/^[0-9]/.test(name)) {
    name = `image_${name}`;
  }

  if (name.length > 64) {
    name = name.slice(0, 64);
  }

  return name;
}

export function isValidCIdentifier(value) {
  return /^[a-zA-Z_][a-zA-Z0-9_]{0,63}$/.test(String(value));
}

function uppercaseIdentifier(identifier) {
  return identifier.toUpperCase();
}

export function createHeader({
  identifier,
  width,
  height,
  data,
  sourceName = "image",
  generatedAt = new Date(),
}) {
  if (!(data instanceof Uint8Array)) {
    throw new TypeError("data must be a Uint8Array");
  }

  if (!isValidCIdentifier(identifier)) {
    throw new Error("identifier is not a valid C identifier");
  }

  if (data.length !== width * height * 2) {
    throw new Error("RGB565 data length does not match image dimensions");
  }

  const macro = `${uppercaseIdentifier(identifier)}_H`;
  const widthMacro = `${uppercaseIdentifier(identifier)}_WIDTH`;
  const heightMacro = `${uppercaseIdentifier(identifier)}_HEIGHT`;
  const sizeMacro = `${uppercaseIdentifier(identifier)}_DATA_SIZE`;
  const timestamp = generatedAt.toISOString().replace(/\.\d{3}Z$/, "Z");
  const safeSource = String(sourceName).replace(/[\r\n*]/g, " ");
  const lines = [
    "#ifndef " + macro,
    "#define " + macro,
    "",
    "#include <stdint.h>",
    "",
    "/*",
    " * Generated by Pixel2Panel v0.1.0",
    ` * Source: ${safeSource}`,
    ` * Generated: ${timestamp}`,
    " * Format: RGB565, high byte first (STM32 little-endian compatible)",
    " */",
    "",
    `#define ${widthMacro} ${width}U`,
    `#define ${heightMacro} ${height}U`,
    `#define ${sizeMacro} (${widthMacro} * ${heightMacro} * 2U)`,
    "",
    `const uint8_t ${identifier}[${sizeMacro}] =`,
    "{",
  ];

  for (let offset = 0; offset < data.length; offset += 16) {
    const chunk = Array.from(data.subarray(offset, offset + 16), (value) =>
      `0x${value.toString(16).toUpperCase().padStart(2, "0")}U`,
    );
    lines.push(`  ${chunk.join(", ")},`);
  }

  lines.push("};", "", `#endif /* ${macro} */`, "");
  return lines.join("\n");
}

export function createIco(pngBytes, size = 256) {
  if (!(pngBytes instanceof Uint8Array)) {
    throw new TypeError("pngBytes must be a Uint8Array");
  }

  if (!Number.isInteger(size) || size < 1 || size > 256) {
    throw new RangeError("ICO size must be between 1 and 256");
  }

  const header = new Uint8Array(22);
  const view = new DataView(header.buffer);
  view.setUint16(0, 0, true);
  view.setUint16(2, 1, true);
  view.setUint16(4, 1, true);
  header[6] = size === 256 ? 0 : size;
  header[7] = size === 256 ? 0 : size;
  header[8] = 0;
  header[9] = 0;
  view.setUint16(10, 1, true);
  view.setUint16(12, 32, true);
  view.setUint32(14, pngBytes.length, true);
  view.setUint32(18, header.length, true);

  const output = new Uint8Array(header.length + pngBytes.length);
  output.set(header);
  output.set(pngBytes, header.length);
  return output;
}

export function formatBytes(bytes) {
  if (bytes < 1024) {
    return `${bytes} B`;
  }

  if (bytes < 1024 * 1024) {
    return `${(bytes / 1024).toFixed(1).replace(/\.0$/, "")} KB`;
  }

  return `${(bytes / (1024 * 1024)).toFixed(1).replace(/\.0$/, "")} MB`;
}

export function clampDimension(value) {
  const numeric = Math.round(Number(value));
  if (!Number.isFinite(numeric)) {
    return null;
  }

  if (numeric < 16 || numeric > MAX_DIMENSION) {
    return null;
  }

  return numeric;
}
